    private static final int TOTAL_CUBES = CUBE_FROM.length;

    public CustomModels() {
        super("CustomModels", "Renders custom 3D models on players.", ModuleCategory.VISUAL);
        instance = this;
    }

    public static CustomModels getInstance() {
        return instance;
    }

    public static boolean shouldHidePlayer(Player player) {
        CustomModels cm = instance;
        return cm != null && cm.isEnabled() && cm.shouldRender(player);
    }

    private boolean shouldRender(Player player) {
        Minecraft mc = Minecraft.getInstance();
        if (player == mc.player) {
            return targets.isSelected("Me");
        }
        if (FriendUtils.isFriend(player)) {
            return targets.isSelected("Friends");
        }
        return targets.isSelected("Players");
    }

    @SubscribeEvent
    private void onWorldRender(WorldRenderEvent event) {
        Minecraft mc = Minecraft.getInstance();
        if (mc.level == null || mc.player == null || mc.gameRenderer == null) return;

        float tickDelta = event.getTickDelta();
        Vec3 camera = Render3D.lastCameraPos;
        PoseStack stack = event.getStack();
        if (camera == null) return;

        boolean firstPerson = mc.options.getCameraType().isFirstPerson();

        for (Player player : mc.level.players()) {
            if (!player.isAlive()) continue;
            if (player == mc.player && firstPerson) continue;
            if (!shouldRender(player)) continue;

            try {
                renderModel(stack, player, tickDelta, camera, mc);
            } catch (Exception ignored) {
            }
        }
    }

    private void renderModel(PoseStack stack, Player player, float tickDelta, Vec3 camera, Minecraft mc) {
        MultiBufferSource.BufferSource provider = mc.renderBuffers().bufferSource();

        double x = Mth.lerp(tickDelta, player.xo, player.getX()) - camera.x;
        double y = Mth.lerp(tickDelta, player.yo, player.getY()) - camera.y;
        double z = Mth.lerp(tickDelta, player.zo, player.getZ()) - camera.z;

        float bodyYaw = Mth.rotLerp(tickDelta, player.yBodyRotO, player.yBodyRot);

        float walkBob = 0f, walkSway = 0f, armSwing = 0f;
        if (walkAnim.getValue()) {
            float time = (float) (player.tickCount + tickDelta) * 0.15f;
            float move = Mth.clamp((float) player.getDeltaMovement().horizontalDistance() * 5f, 0f, 1f);
            float speed = 1f + move * 2f;
            float amp = 0.5f + move * 0.5f;
            walkBob = Mth.sin(time * 3f * speed) * 0.08f * amp;
            walkSway = Mth.sin(time * 1.5f * speed) * 0.04f * amp;
            armSwing = Mth.sin(time * 2.5f * speed) * 0.4f * amp;
        }

        float headPitch = 0f, headYawDelta = 0f;
        if (headRot.getValue()) {
            headPitch = Mth.rotLerp(tickDelta, player.xRotO, player.getXRot());
            float headYaw = Mth.rotLerp(tickDelta, player.yHeadRotO, player.yHeadRot);
            headYawDelta = headYaw - bodyYaw;
        }

        stack.pushPose();
        stack.translate(x, y, z);
        stack.mulPose(com.mojang.math.Axis.YP.rotationDegrees(180f - bodyYaw));
        stack.translate(offsetX.getFloat(), offsetY.getFloat() + walkBob, offsetZ.getFloat() + walkSway);
        stack.scale(SCALE, SCALE, SCALE);

        VertexConsumer consumer = provider.getBuffer(MODEL_TYPE);
        int color = 0xFFFFFFFF;

        int startCube = fullModel.getValue() ? 0 : 11;
        for (int i = startCube; i < TOTAL_CUBES; i++) {
            boolean isHead = i == 0;
            boolean isLeftArm = i == 3 || i == 4;
            boolean isRightArm = i == 5 || i == 6;
            boolean needsTransform = (isHead && headRot.getValue()) || (walkAnim.getValue() && (isLeftArm || isRightArm));

            if (needsTransform) {
                stack.pushPose();
                if (isHead) {
                    stack.translate(0f, 24f, 0f);
                    stack.mulPose(com.mojang.math.Axis.XP.rotationDegrees(headPitch));
                    stack.mulPose(com.mojang.math.Axis.YP.rotationDegrees(headYawDelta));
                    stack.translate(0f, -24f, 0f);
                } else if (isLeftArm) {
                    stack.translate(-5.5f, 24f, 0f);
                    stack.mulPose(com.mojang.math.Axis.XP.rotationDegrees(armSwing * 50f));
                    stack.translate(5.5f, -24f, 0f);
                } else if (isRightArm) {
                    stack.translate(5.5f, 24f, 0f);
                    stack.mulPose(com.mojang.math.Axis.XP.rotationDegrees(-armSwing * 50f));
                    stack.translate(-5.5f, -24f, 0f);
                }
            }

            PoseStack.Pose pose = stack.last();
            float x0 = CUBE_FROM[i][0], y0 = CUBE_FROM[i][1], z0 = CUBE_FROM[i][2];
            float x1 = CUBE_TO[i][0], y1 = CUBE_TO[i][1], z1 = CUBE_TO[i][2];

            for (int face = 0; face < 6; face++) {
                int uvFace = face == 0 ? 1 : face == 1 ? 0 : face;
                float[] uv = FACE_UVS[i][uvFace];
                if (uv == null) continue;

                float u0 = uv[0] / ATLAS_SIZE, v0 = uv[1] / ATLAS_SIZE;
                float u2 = uv[2] / ATLAS_SIZE, v2 = uv[3] / ATLAS_SIZE;

                switch (face) {
                    case 0:
                        consumer.addVertex(pose, x0, y0, z0).setUv(u0, v2).setColor(color);
                        consumer.addVertex(pose, x1, y0, z0).setUv(u2, v2).setColor(color);
                        consumer.addVertex(pose, x1, y1, z0).setUv(u2, v0).setColor(color);
                        consumer.addVertex(pose, x0, y1, z0).setUv(u0, v0).setColor(color);
                        break;
                    case 1:
                        consumer.addVertex(pose, x1, y0, z1).setUv(u0, v2).setColor(color);
                        consumer.addVertex(pose, x0, y0, z1).setUv(u2, v2).setColor(color);
                        consumer.addVertex(pose, x0, y1, z1).setUv(u2, v0).setColor(color);
                        consumer.addVertex(pose, x1, y1, z1).setUv(u0, v0).setColor(color);
                        break;
                    case 2:
                        consumer.addVertex(pose, x1, y0, z0).setUv(u0, v2).setColor(color);
                        consumer.addVertex(pose, x1, y0, z1).setUv(u2, v2).setColor(color);
                        consumer.addVertex(pose, x1, y1, z1).setUv(u2, v0).setColor(color);
                        consumer.addVertex(pose, x1, y1, z0).setUv(u0, v0).setColor(color);
                        break;
                    case 3:
                        consumer.addVertex(pose, x0, y0, z1).setUv(u0, v2).setColor(color);
                        consumer.addVertex(pose, x0, y0, z0).setUv(u2, v2).setColor(color);
                        consumer.addVertex(pose, x0, y1, z0).setUv(u2, v0).setColor(color);
                        consumer.addVertex(pose, x0, y1, z1).setUv(u0, v0).setColor(color);
                        break;
                    case 4:
                        consumer.addVertex(pose, x0, y1, z0).setUv(u0, v0).setColor(color);
                        consumer.addVertex(pose, x1, y1, z0).setUv(u2, v0).setColor(color);
                        consumer.addVertex(pose, x1, y1, z1).setUv(u2, v2).setColor(color);
                        consumer.addVertex(pose, x0, y1, z1).setUv(u0, v2).setColor(color);
                        break;
                    case 5:
                        consumer.addVertex(pose, x0, y0, z1).setUv(u0, v0).setColor(color);
                        consumer.addVertex(pose, x1, y0, z1).setUv(u2, v0).setColor(color);
                        consumer.addVertex(pose, x1, y0, z0).setUv(u2, v2).setColor(color);
                        consumer.addVertex(pose, x0, y0, z0).setUv(u0, v2).setColor(color);
                        break;
                }
            }

            if (needsTransform) {
                stack.popPose();
            }
        }

        stack.popPose();
        provider.endBatch(MODEL_TYPE);
    }
